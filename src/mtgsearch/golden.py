"""Golden fixture shared by the Python and TypeScript implementations.

The request-time code exists twice: here (the reference, checked against Scryfall) and in
`netlify/lib/` (what the Netlify function runs). This module writes what the reference
produces for a fixed set of inputs; the TypeScript tests must reproduce it exactly, and a
Python test fails when the committed file is stale.

    mtgsearch golden            rewrite fixtures/golden.json
"""

import json
from pathlib import Path

from . import nl
from .catalog import type_word_set
from .documents import fold, plain
from .search import _split_words, is_plain_words
from .syntax import QueryError, Unsupported, lower, parse
from .syntax.parser import Keyword

ROOT = Path(__file__).resolve().parents[2]
FIXTURE = ROOT / "fixtures" / "golden.json"
QUERY_FILES = ["conformance/queries.txt", "conformance/heldout.txt", "fixtures/extra_queries.txt"]

NORMALIZE = [
    "Lim-Dûl's Vault", "Séance", "Jötun Grunt", "Æther Vial", "Dandân", "Ifh-Bíff Efreet", "Khabál Ghoul",
    "Junún Efreet", "Ghazbán Ogre", "El-Hajjâj", "Márton Stromgald", "Bösium Strip", "Song of Eärendil",
    "Troll of Khazad-dûm", "Urza's Tower", "Fire // Ice", "Who // What // When // Where // Why",
    "  Mixed   CASE\twith\nspaces ", "Borrowing 100,000 Arrows", "+2 Mace", "_____", "Ach! Hans, Run!",
    "Kongming, \"Sleeping Dragon\"", "Sword of Dungeons & Dragons", "ǅ ﬁ ½ ①", "İstanbul ẞ", "",
]  # fmt: skip


def _queries() -> list[str]:
    seen, out = set(), []
    for name in QUERY_FILES:
        for line in (ROOT / name).read_text(encoding="utf-8").splitlines():
            query = line.strip()
            if query and not query.startswith("#") and query not in seen:
                seen.add(query)
                out.append(query)
    return out


def _eval_queries() -> list[str]:
    data = json.loads((ROOT / "eval" / "queries.json").read_text(encoding="utf-8"))
    return [item["q"] for key in ("descriptive", "numeric", "jargon", "art") for item in data[key]]


def _syntax(query: str) -> dict:
    try:
        ast = parse(query)
        predicate, options = lower(ast)
    except Unsupported as e:
        return {"query": query, "error": "Unsupported", "message": str(e)}
    except QueryError:
        return {"query": query, "error": "QueryError"}  # the message is never shown to a user
    split = _split_words(ast)
    return {
        "query": query,
        "ir": predicate,
        "options": {
            "include_extras": options.include_extras,
            "order": options.order,
            "descending": options.descending,
        },
        "plain": is_plain_words(ast),
        "split": None
        if split is None
        else {
            "keywords": [k.key if isinstance(k, Keyword) else f"!{k.text}" for k in split[0]],
            "words": [w.text for w in split[1]],
        },
    }


def build() -> dict:
    plain_english = _eval_queries()
    extra_nl = (ROOT / "fixtures" / "extra_plain_english.txt").read_text(encoding="utf-8").splitlines()
    plain_english += [q for q in extra_nl if q.strip() and not q.startswith("#")]
    everything = _queries() + plain_english
    return {
        "_note": "Generated by `mtgsearch golden` from the Python reference. Do not edit by hand.",
        "catalog": sorted(type_word_set()),
        "normalize": [{"text": t, "fold": fold(t), "plain": plain(t)} for t in NORMALIZE],
        "syntax": [_syntax(q) for q in everything],
        "nl": [
            {"query": q, "predicate": e.predicate, "notes": e.notes}
            for q in plain_english
            for e in [nl.extract(q)]
        ],
    }


def dumps(data: dict) -> str:
    return json.dumps(data, indent=1, ensure_ascii=False) + "\n"


def write(path: Path = FIXTURE) -> int:
    data = build()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(dumps(data), encoding="utf-8")
    return len(data["syntax"]) + len(data["nl"]) + len(data["normalize"])
