// Regression snapshot of what the query compiler produces.
//
//   npm run golden            rewrite fixtures/reference.json
//   npm run golden -- --check fail if the committed file is not what the code produces now
//
// fixtures/reference.json holds the compiled predicate for every conformance query, every
// evaluation query and a file of edge cases. It was first written by the original Python
// implementation, whose output had been checked against Scryfall, and this code reproduced it
// exactly. A change to it should be a deliberate, reviewed change in search behaviour.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { lower } from "./lower.ts";
import { extract } from "./nl.ts";
import { parse, QueryError, Unsupported } from "./parser.ts";
import { isPlainWords, splitWords } from "./search.ts";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
export const REFERENCE = `${ROOT}fixtures/reference.json`;
const QUERY_FILES = [
  "conformance/queries.txt",
  "conformance/heldout.txt",
  "conformance/printings.txt",
  "conformance/prices.txt",
  "conformance/mana.txt",
  "conformance/mana_heldout.txt",
  "conformance/shortcuts.txt",
  "conformance/heldout2.txt",
  "conformance/regex.txt",
  "conformance/names.txt",
  "conformance/blocks.txt",
  "fixtures/extra_queries.txt",
];

function lines(path: string): string[] {
  return readFileSync(ROOT + path, "utf8")
    .split("\n")
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith("#"));
}

export function compile(query: string) {
  try {
    const ast = parse(query);
    const [ir, options] = lower(ast);
    const split = splitWords(ast);
    return {
      query,
      ir,
      options: {
        include_extras: options.includeExtras,
        order: options.order,
        descending: options.descending,
        // only present for queries answered from the printings collection
        ...(options.printings ? { printings: true, unique: options.unique, prefer: options.prefer } : {}),
      },
      plain: isPlainWords(ast),
      split: split && {
        keywords: split.keywords.map((k) => (k.kind === "keyword" ? k.key : `!${k.text}`)),
        words: split.words.map((w) => w.text),
      },
    };
  } catch (error) {
    if (error instanceof Unsupported) return { query, error: "Unsupported", message: error.message };
    if (error instanceof QueryError) return { query, error: "QueryError" }; // the message is never shown
    throw error;
  }
}

export function build() {
  const syntax = [...new Set(QUERY_FILES.flatMap(lines))];
  const evaluation = JSON.parse(readFileSync(`${ROOT}eval/queries.json`, "utf8"));
  const plainEnglish: string[] = [
    ...["descriptive", "numeric", "jargon", "art"].flatMap((key) => evaluation[key].map((item: { q: string }) => item.q)),
    ...lines("fixtures/extra_plain_english.txt"),
  ];
  return {
    _note: "Generated by `npm run golden`. A regression snapshot: review any change to it as a change in search behaviour.",
    syntax: [...syntax, ...plainEnglish].map(compile),
    nl: plainEnglish.map((query) => {
      const { predicate, notes } = extract(query);
      return { query, predicate, notes };
    }),
  };
}

export const serialize = (data: unknown) => `${JSON.stringify(data, null, 1)}\n`;

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = serialize(build());
  if (process.argv.includes("--check")) {
    if (readFileSync(REFERENCE, "utf8") !== text) {
      console.error("fixtures/reference.json is stale: run `npm run golden` and review the diff");
      process.exit(1);
    }
    console.log("fixtures/reference.json is current");
  } else {
    writeFileSync(REFERENCE, text);
    const data = build();
    console.log(`wrote ${data.syntax.length + data.nl.length} cases to fixtures/reference.json`);
  }
}
